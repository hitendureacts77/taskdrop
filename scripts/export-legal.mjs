#!/usr/bin/env node
/**
 * Render the Terms of Service and Privacy Policy to Markdown for a lawyer.
 *
 *   npm run legal:export
 *
 * The text lives in one place, apps/mobile/src/legal/documents.ts, which the app
 * shows. This compiles that file (and company.ts) to a temp folder and renders
 * it with a [BRACKETED PLACEHOLDER] for every company detail that is still
 * unset, so the reviewer sees what is missing instead of the app's fallback
 * wording ("through Help & support in the app").
 *
 * Writes docs/legal/TERMS_OF_SERVICE.md and docs/legal/PRIVACY_POLICY.md.
 */
import { execFileSync } from 'node:child_process';
import { mkdirSync, mkdtempSync, rmSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const src = join(root, 'apps/mobile/src/legal');
const out = join(root, 'docs/legal');
const tmp = mkdtempSync(join(tmpdir(), 'taskdrop-legal-'));

// Placeholders go in through the same variables the app reads at build time.
const placeholders = {
  EXPO_PUBLIC_LEGAL_ENTITY: '[LEGAL ENTITY NAME]',
  EXPO_PUBLIC_LEGAL_ADDRESS: '[REGISTERED ADDRESS]',
  EXPO_PUBLIC_LEGAL_EMAIL: '[SUPPORT / PRIVACY EMAIL]',
  EXPO_PUBLIC_GRIEVANCE_OFFICER_NAME: '[GRIEVANCE OFFICER NAME]',
  EXPO_PUBLIC_GRIEVANCE_OFFICER_EMAIL: '[GRIEVANCE OFFICER EMAIL]',
  EXPO_PUBLIC_LEGAL_JURISDICTION: '[CITY OF JURISDICTION]',
};
for (const [k, v] of Object.entries(placeholders)) process.env[k] = process.env[k] || v;

try {
  const tsc = createRequire(import.meta.url).resolve('typescript/bin/tsc');
  execFileSync(
    process.execPath,
    [tsc, join(src, 'documents.ts'), join(src, 'company.ts'), '--outDir', tmp, '--module', 'commonjs', '--target', 'es2020', '--skipLibCheck', '--types', 'node'],
    { stdio: 'inherit', cwd: root },
  );
  writeFileSync(join(tmp, 'package.json'), '{"type":"commonjs"}');
  const { TERMS, PRIVACY } = createRequire(import.meta.url)(join(tmp, 'documents.js'));

  const render = (doc) => {
    const lines = [`# ${doc.title}`, '', `_Last updated ${doc.updated}._`, '', doc.intro, ''];
    doc.sections.forEach((s, i) => {
      lines.push(`## ${i + 1}. ${s.heading}`, '');
      for (const b of s.body) {
        if (typeof b === 'string') lines.push(b, '');
        else lines.push(...b.list.map((x) => `- ${x}`), '');
      }
    });
    lines.push(
      '---',
      '',
      '_DRAFT for review by a qualified lawyer. Rendered from `apps/mobile/src/legal/documents.ts`; every statement is traced to code in `docs/LEGAL_AUDIT.md`. Do not edit this file by hand: change `documents.ts` and run `npm run legal:export`._',
      '',
    );
    return lines.join('\n');
  };

  mkdirSync(out, { recursive: true });
  writeFileSync(join(out, 'TERMS_OF_SERVICE.md'), render(TERMS));
  writeFileSync(join(out, 'PRIVACY_POLICY.md'), render(PRIVACY));
  console.log(`Wrote ${join(out, 'TERMS_OF_SERVICE.md')} and ${join(out, 'PRIVACY_POLICY.md')}`);
} finally {
  rmSync(tmp, { recursive: true, force: true });
}
